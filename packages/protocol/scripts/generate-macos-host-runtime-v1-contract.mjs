function swiftArray(values) {
  if (!Array.isArray(values) || values.some((value) => typeof value !== 'string')) {
    throw new Error('macOS host runtime contract array must contain only strings');
  }
  return `[${values.map((value) => JSON.stringify(value)).join(', ')}]`;
}

function validateContract(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error('macOS host runtime contract must be an object');
  }
  const uniqueStringArray = (name, values) => {
    if (!Array.isArray(values) || values.some((item) => typeof item !== 'string')) {
      throw new Error(`${name} must contain only strings`);
    }
    if (new Set(values).size !== values.length) {
      throw new Error(`${name} must not contain duplicates`);
    }
  };
  for (const name of [
    'operations', 'commonRequestKeys', 'commonResponseKeys', 'eventKeys', 'providers',
    'executionStates', 'treeTerminationStates', 'runtimeAvailabilityStates',
    'runtimeAvailabilityReasons', 'runtimeAdmissionStates', 'runtimeAvailabilityTupleKeys',
    'forbiddenPayloadKeys',
  ]) uniqueStringArray(name, value[name]);
  uniqueStringArray('transportHandshake.requestKeys', value.transportHandshake?.requestKeys);
  uniqueStringArray('transportHandshake.responseKeys', value.transportHandshake?.responseKeys);
  uniqueStringArray('transportHandshake.failureResponseKeys', value.transportHandshake?.failureResponseKeys);
  uniqueStringArray('turnStream.actions', value.turnStream?.actions);
  uniqueStringArray('turnStream.gates', value.turnStream?.gates);
  if (!Number.isSafeInteger(value.turnStream?.maxRequestBytes)
      || value.turnStream.maxRequestBytes <= 0
      || value.turnStream.maxRequestBytes > value.maxRequestBytes
      || !Number.isSafeInteger(value.turnStream?.maxResponseBytes)
      || value.turnStream.maxResponseBytes <= 0
      || value.turnStream.maxResponseBytes > value.maxResponseBytes
      || !Number.isSafeInteger(value.turnStream?.maxFrames)
      || value.turnStream.maxFrames <= 0
      || !Number.isSafeInteger(value.turnStream?.maxTurnBytes)
      || value.turnStream.maxTurnBytes <= 0
      || value.turnStream.maxTurnBytes > value.turnStream.maxResponseBytes) {
    throw new Error('turn stream limits must be positive integers within transport limits');
  }
  if (!Number.isSafeInteger(value.transportHandshake.maxRequestBytes)
      || value.transportHandshake.maxRequestBytes <= 0
      || value.transportHandshake.maxRequestBytes > value.maxRequestBytes
      || !Number.isSafeInteger(value.transportHandshake.maxResponseBytes)
      || value.transportHandshake.maxResponseBytes <= 0
      || value.transportHandshake.maxResponseBytes > value.maxResponseBytes) {
    throw new Error('transport handshake byte limits must be positive integers within outer limits');
  }
  const operationSet = new Set(value.operations);
  for (const mapName of ['requestPayloadKeySets', 'responsePayloadKeySets']) {
    const map = value[mapName];
    if (!map || typeof map !== 'object' || Array.isArray(map)
        || !sameSet(new Set(Object.keys(map)), operationSet)) {
      throw new Error(`${mapName} keys must exactly match operations`);
    }
    for (const [operation, keys] of Object.entries(map)) uniqueStringArray(`${mapName}.${operation}`, keys);
  }
  const states = new Set(value.runtimeAvailabilityStates);
  const reasons = new Set(value.runtimeAvailabilityReasons);
  const admissions = new Set(value.runtimeAdmissionStates);
  for (const tuple of value.runtimeAvailabilityTupleKeys) {
    const fields = tuple.split('|');
    if (fields.length !== 3 || !states.has(fields[0]) || !reasons.has(fields[1]) || !admissions.has(fields[2])) {
      throw new Error(`invalid runtime availability tuple: ${tuple}`);
    }
  }
}

function sameSet(left, right) {
  return left.size === right.size && [...left].every((value) => right.has(value));
}

function swiftStringArrayMap(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error('macOS host runtime contract map must be an object');
  }
  const entries = Object.entries(value).map(([key, values]) => (
    `        ${JSON.stringify(key)}: ${swiftArray(values)}`
  ));
  return `[\n${entries.join(',\n')}\n    ]`;
}
