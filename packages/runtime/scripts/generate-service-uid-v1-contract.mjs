import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const packageDirectory = join(scriptDirectory, '..');
const contractPath = join(packageDirectory, 'contracts/macos-service-uid-v1/contract.json');
const tsPath = join(packageDirectory, 'src/generated/macos-service-uid-v1-contract.ts');
const headerPath = join(packageDirectory, 'native/service-uid/generated/macos-service-uid-v1-contract.h');
const swiftPath = join(
  packageDirectory,
  '../../apps/macos/Sources/RoundTableContracts/Generated/MacOSServiceUIDV1Generated.swift',
);

const bytes = await readFile(contractPath);
const text = bytes.toString('utf8');
const contract = JSON.parse(text);
const hash = createHash('sha256').update(bytes).digest('hex');
const json = JSON.stringify(contract);
const ts = `// Generated by scripts/generate-service-uid-v1-contract.mjs.\n`
  + `export const MACOS_SERVICE_UID_V1_CORPUS_SHA256 = '${hash}' as const;\n`
  + `export const MACOS_SERVICE_UID_V1_CORPUS = Object.freeze(${json} as const);\n`;
const header = `/* Generated by scripts/generate-service-uid-v1-contract.mjs. */\n`
  + `#ifndef ROUNDTABLE_MACOS_SERVICE_UID_V1_CONTRACT_H\n#define ROUNDTABLE_MACOS_SERVICE_UID_V1_CONTRACT_H\n\n`
  + `#define RT_MACOS_SERVICE_UID_V1_CORPUS_SHA256 "${hash}"\n`
  + `#define RT_MACOS_SERVICE_UID_V1_CONTRACT "${contract.contract}"\n`
  + `#define RT_MACOS_SERVICE_UID_V1_VERSION ${contract.version}U\n`
  + `#define RT_MACOS_SERVICE_UID_V1_MAX_CONCURRENCY ${contract.maxConcurrency}U\n`
  + `#define RT_MACOS_SERVICE_UID_V1_SECRET_TRANSPORT "${contract.secretTransport}"\n\n`
  + `#endif\n`;
const swift = `// Generated by packages/runtime/scripts/generate-service-uid-v1-contract.mjs.\n`
  + `// Do not edit by hand.\n\n`
  + `import Foundation\n\n`
  + `public enum MacOSServiceUIDV1Generated {\n`
  + `    public static let corpusSHA256 = ${swiftString(hash)}\n`
  + `    public static let canonicalJSON = ${swiftString(text)}\n`
  + `    public static let contract = ${swiftString(contract.contract)}\n`
  + `    public static let version = ${contract.version}\n`
  + `    public static let maxConcurrency = ${contract.maxConcurrency}\n`
  + `    public static let secretTransport = ${swiftString(contract.secretTransport)}\n`
  + `    public static let requests = ${swiftValue(contract.requests)}\n`
  + `    public static let requestKeySets = ${swiftValue(contract.requestKeySets)}\n`
  + `    public static let nestedKeySets = ${swiftValue(contract.nestedKeySets)}\n`
  + `    public static let responseKeySets = ${swiftValue(contract.responseKeySets)}\n`
  + `    public static let seatKeySet = ${swiftValue(contract.seatKeySet)}\n`
  + `    public static let workloads = ${swiftValue(contract.workloads)}\n`
  + `    public static let seatStates = ${swiftValue(contract.seatStates)}\n`
  + `    public static let cleanupDisposition = ${swiftString(contract.cleanupDisposition)}\n`
  + `    public static let stopReasons = ${swiftValue(contract.stopReasons)}\n`
  + `    public static let errors = ${swiftValue(contract.errors)}\n`
  + `}\n`;

if (process.argv[2] === '--check') {
  const [existingTs, existingHeader, existingSwift] = await Promise.all([
    readFile(tsPath, 'utf8').catch(() => null),
    readFile(headerPath, 'utf8').catch(() => null),
    readFile(swiftPath, 'utf8').catch(() => null),
  ]);
  if (existingTs !== ts || existingHeader !== header || existingSwift !== swift) {
    throw new Error('generated service UID v1 contract is stale; run the generator');
  }
  process.stdout.write('service-uid-v1 contract generated artifacts are current\n');
  process.exit(0);
}

await mkdir(dirname(tsPath), { recursive: true, mode: 0o755 });
await mkdir(dirname(headerPath), { recursive: true, mode: 0o755 });
await mkdir(dirname(swiftPath), { recursive: true, mode: 0o755 });
await writeFile(tsPath, ts, 'utf8');
await writeFile(headerPath, header, 'utf8');
await writeFile(swiftPath, swift, 'utf8');

function swiftString(value) {
  return JSON.stringify(value)
    .replaceAll('\\u2028', '\\u{2028}')
    .replaceAll('\\u2029', '\\u{2029}');
}

function swiftValue(value, indentation = 4) {
  if (typeof value === 'string') return swiftString(value);
  if (Number.isSafeInteger(value)) return String(value);
  if (Array.isArray(value)) {
    return `[${value.map((entry) => swiftValue(entry, indentation + 4)).join(', ')}]`;
  }
  if (value && typeof value === 'object') {
    const padding = ' '.repeat(indentation);
    const childPadding = ' '.repeat(indentation + 4);
    const entries = Object.entries(value).map(([key, entry]) => (
      `${childPadding}${swiftString(key)}: ${swiftValue(entry, indentation + 4)}`
    ));
    return `[\n${entries.join(',\n')}\n${padding}]`;
  }
  throw new Error('service UID v1 contract contains an unsupported Swift value');
}
